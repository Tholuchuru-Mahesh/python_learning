import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:uuid/uuid.dart';
import '../models/bill.dart';
import '../models/cart_item.dart';
import '../services/api_service.dart';

class BillingState {
  final List<Bill> bills;
  final bool isLoading;
  final String? errorMessage;
  final Bill? lastCompletedBill;

  BillingState({
    this.bills = const [],
    this.isLoading = false,
    this.errorMessage,
    this.lastCompletedBill,
  });

  BillingState copyWith({
    List<Bill>? bills,
    bool? isLoading,
    String? errorMessage,
    Bill? lastCompletedBill,
  }) {
    return BillingState(
      bills: bills ?? this.bills,
      isLoading: isLoading ?? this.isLoading,
      errorMessage: errorMessage,
      lastCompletedBill: lastCompletedBill ?? this.lastCompletedBill,
    );
  }
}

class BillingNotifier extends StateNotifier<BillingState> {
  final ApiService _api = ApiService();
  final _uuid = const Uuid();

  BillingNotifier() : super(BillingState()) {
    fetchBills();
  }

  Future<void> fetchBills({String? startDate, String? endDate}) async {
    state = state.copyWith(isLoading: true, errorMessage: null);
    try {
      final queryParams = <String, String>{'limit': '50'};
      if (startDate != null) queryParams['startDate'] = startDate;
      if (endDate != null) queryParams['endDate'] = endDate;

      final res = await _api.get('/api/billing', queryParams: queryParams);
      final rawBills = (res['bills'] as List<dynamic>?) ?? [];
      final bills = rawBills.map((e) => Bill.fromJson(e as Map<String, dynamic>)).toList();

      state = state.copyWith(bills: bills, isLoading: false);
    } catch (e) {
      state = state.copyWith(isLoading: false, errorMessage: e.toString());
    }
  }

  Future<Bill?> createBill({
    required List<CartItem> items,
    double discountAmount = 0.0,
    String? notes,
  }) async {
    state = state.copyWith(isLoading: true, errorMessage: null);
    try {
      // PRD §9.3 & §10.4 Idempotency key generated by client
      final idempotencyKey = _uuid.v4();

      final payload = {
        'idempotencyKey': idempotencyKey,
        'discountAmount': discountAmount,
        'notes': notes,
        'items': items.map((i) => {
          'productId': i.product.id,
          'quantity': i.quantity,
          'unitPrice': i.unitPrice,
        }).toList(),
      };

      final res = await _api.post('/api/billing', body: payload);
      final completedBill = Bill.fromJson(res as Map<String, dynamic>);

      state = state.copyWith(
        isLoading: false,
        lastCompletedBill: completedBill,
        bills: [completedBill, ...state.bills],
      );

      return completedBill;
    } catch (e) {
      state = state.copyWith(isLoading: false, errorMessage: e.toString());
      return null;
    }
  }

  Future<Bill?> reprintBill(String billId) async {
    try {
      final res = await _api.post('/api/billing/$billId/reprint');
      final reprint = Bill.fromJson(res as Map<String, dynamic>);
      return reprint;
    } catch (e) {
      state = state.copyWith(errorMessage: e.toString());
      return null;
    }
  }

  Future<Bill?> getBillDetails(String billId) async {
    try {
      final res = await _api.get('/api/billing/$billId');
      return Bill.fromJson(res as Map<String, dynamic>);
    } catch (e) {
      state = state.copyWith(errorMessage: e.toString());
      return null;
    }
  }
}

final billingProvider =
    StateNotifierProvider<BillingNotifier, BillingState>((ref) {
  return BillingNotifier();
});

